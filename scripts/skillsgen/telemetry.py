"""Skills-invoked telemetry block, generated into every SKILL.md.

Each skill tells the agent to prefix its `databricks` CLI calls with
`DATABRICKS_SKILLS_INVOKED=<skills>`. The CLI sends that value as the
`X-Databricks-Skills-Invoked` HTTP header. Marketplace installs serve the newest
skills to every CLI version, and older CLIs ignore the unknown env var, so the
skills need no CLI version gate.

The block is written into the source SKILL.md files, not only the bundles,
because `databricks aitools install` fetches the root `skills/` directly.
"""

from pathlib import Path

from skillsgen.discovery import iter_all_skill_dirs

BLOCK_START = (
    "<!-- BEGIN databricks-skills-invoked: generated by scripts/skills.py generate, do not edit -->"
)
BLOCK_END = "<!-- END databricks-skills-invoked -->"

SKILLS_INVOKED_TEMPLATE = """\
**Usage telemetry:** prefix every `databricks` CLI command you run for this skill with
`DATABRICKS_SKILLS_INVOKED=<skills>`, where `<skills>` is a comma-separated list of every
Databricks skill loaded for this task, including `{skill}`. Example:
`DATABRICKS_SKILLS_INVOKED={example} databricks current-user me`. It only reports which
skills were used: it never changes what the command does, and older CLIs ignore it. In
PowerShell, set it for the session instead (`$env:DATABRICKS_SKILLS_INVOKED="{skill}"`).
Use it only on commands you run yourself, not in scripts or code you write for the user."""


def render_block(skill_name: str) -> str:
    """Return the full delimited block for one skill."""
    example = skill_name if skill_name == "databricks-core" else f"databricks-core,{skill_name}"
    body = SKILLS_INVOKED_TEMPLATE.format(skill=skill_name, example=example)
    return f"{BLOCK_START}\n{body}\n{BLOCK_END}"


def _split_frontmatter(text: str) -> tuple[str, str]:
    """Split SKILL.md into (frontmatter including both '---' lines, body)."""
    if not text.startswith("---\n"):
        return "", text
    end = text.find("\n---\n", 4)
    if end == -1:
        return "", text
    cut = end + len("\n---\n")
    return text[:cut], text[cut:]


def _strip_block(body: str) -> str:
    """Remove an existing block (and the blank line after it), if present."""
    start = body.find(BLOCK_START)
    if start == -1:
        return body
    end = body.find(BLOCK_END, start)
    if end == -1:
        raise ValueError("unterminated databricks-skills-invoked block")
    end += len(BLOCK_END)
    while end < len(body) and body[end] == "\n":
        end += 1
    return body[:start] + body[end:]


def apply_block(text: str, skill_name: str) -> str:
    """Return SKILL.md text with the block inserted or refreshed.

    The block goes right after the H1 title when the body opens with one,
    otherwise right after the frontmatter.
    """
    frontmatter, body = _split_frontmatter(text)
    body = _strip_block(body)
    block = render_block(skill_name) + "\n\n"

    leading = len(body) - len(body.lstrip("\n"))
    rest = body[leading:]
    if rest.startswith("# "):
        title, _, after = rest.partition("\n")
        return frontmatter + body[:leading] + title + "\n\n" + block + after.lstrip("\n")
    return frontmatter + body[:leading] + block + rest


def ensure_skills_invoked_block(repo_root: Path) -> int:
    """Write or refresh the block in every stable and experimental SKILL.md.

    Returns the number of SKILL.md files changed.
    """
    written = 0
    for skill_dir in iter_all_skill_dirs(repo_root):
        path = skill_dir / "SKILL.md"
        text = path.read_text()
        updated = apply_block(text, skill_dir.name)
        if updated != text:
            path.write_text(updated)
            written += 1
    return written


def check_skills_invoked_block(repo_root: Path) -> list[str]:
    """Report skills whose SKILL.md block is missing or stale."""
    errors: list[str] = []
    for skill_dir in iter_all_skill_dirs(repo_root):
        text = (skill_dir / "SKILL.md").read_text()
        if BLOCK_START not in text:
            errors.append(f"Missing skills-invoked telemetry block in skill '{skill_dir.name}'.")
            continue
        try:
            expected = apply_block(text, skill_dir.name)
        except ValueError as err:
            errors.append(f"Invalid skills-invoked block in skill '{skill_dir.name}': {err}.")
            continue
        if expected != text:
            errors.append(f"Stale skills-invoked telemetry block in skill '{skill_dir.name}'.")
    return errors
